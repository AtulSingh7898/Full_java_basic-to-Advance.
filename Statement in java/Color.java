public class Color {
    public static void main(String [] args){
        char ch = 'R';
        switch(ch){
            case 'R': System.out.println("Red");
            break;
            case 'G': System.out.println("Green");
            break;
            case 'B': System.out.println("Blue");
            break;
            default : System.out.println("YOU pick other color ");
        }

    }
}
    

